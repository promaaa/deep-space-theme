"""Build colors.toml for Deep Space and check that it stays readable.

Each colour is written in OKLCH (lightness, chroma, hue). The hues were
measured in backgrounds/01-rings.webp. Lightness and chroma were then set so
text stays readable on the dark background. The script stops if a contrast
floor breaks.

Run from the repository root:  uv run --with numpy python tools/palettes.py
"""
import os, numpy as np

# Hues measured in the picture (OKLCH degrees).
VOID = SILVER = 262        # blue-black space and the ring's greys
BLUE, SKY, VIOLET = 255, 228, 295
VERMILLION, CORAL, GOLD = 28, 50, 92
MINT = 165                 # not in the picture: added so green still means "OK"


def oklch(L, C, H):
    """OKLCH to sRGB hex. Lowers chroma until the colour fits in sRGB."""
    for c in np.linspace(C, 0, 60):
        a, b = c * np.cos(np.radians(H)), c * np.sin(np.radians(H))
        l_, m_, s_ = (np.array([[1, 0.3963377774, 0.2158037573],
                                [1, -0.1055613458, -0.0638541728],
                                [1, -0.0894841775, -1.2914855480]]) @ [L, a, b]) ** 3
        rgb = np.array([[4.0767416621, -3.3077115913, 0.2309699292],
                        [-1.2684380046, 2.6097574011, -0.3413193965],
                        [-0.0041960863, -0.7034186147, 1.7076147010]]) @ [l_, m_, s_]
        if rgb.min() >= -1e-4 and rgb.max() <= 1 + 1e-4:
            srgb = np.where(rgb <= 0.0031308, 12.92 * rgb, 1.055 * np.clip(rgb, 0, 1) ** (1 / 2.4) - 0.055)
            return "#%02x%02x%02x" % tuple(int(round(v * 255)) for v in np.clip(srgb, 0, 1))
    raise ValueError((L, C, H))


def contrast(a, b):
    """WCAG 2 contrast ratio of two hex colours."""
    def lum(h):
        c = np.array([int(h[i:i + 2], 16) / 255 for i in (1, 3, 5)])
        c = np.where(c <= 0.04045, c / 12.92, ((c + 0.055) / 1.055) ** 2.4)
        return c @ [0.2126, 0.7152, 0.0722]
    hi, lo = sorted([lum(a), lum(b)], reverse=True)
    return (hi + 0.05) / (lo + 0.05)


HUES = dict(  # (L, C, H)
    red=(0.67, 0.165, VERMILLION), yellow=(0.86, 0.105, GOLD), orange=(0.75, 0.125, CORAL),
    green=(0.80, 0.095, MINT), cyan=(0.79, 0.085, SKY), blue=(0.72, 0.115, BLUE),
    magenta=(0.74, 0.095, VIOLET), brown=(0.45, 0.085, 38),
)
G = 0.185  # background lightness
COLORS = dict(
    accent=oklch(*HUES["blue"]),
    selection=oklch(G + 0.15, 0.060, BLUE),
    muted=oklch(0.64, 0.030, SILVER),              # ANSI 8: comments, shell suggestions
    background=oklch(G, 0.020, VOID),
    dark_background=oklch(G - 0.03, 0.017, VOID),
    darker_background=oklch(G - 0.06, 0.014, VOID),
    lighter_background=oklch(G + 0.05, 0.024, VOID),
    foreground=oklch(0.88, 0.018, SILVER),         # the ring's lit silver
    dark_foreground=oklch(0.55, 0.030, SILVER),
    light_foreground=oklch(0.80, 0.022, SILVER),
    bright_foreground=oklch(0.965, 0.008, SILVER),  # the ring's white core
    **{k: oklch(*v) for k, v in HUES.items()},
    **{"bright_" + k: oklch(min(L + 0.07, 0.95), C * 0.85, H)
       for k, (L, C, H) in HUES.items() if k not in ("orange", "brown")},
)
SIGNAL = ["red", "green", "yellow", "blue", "magenta", "cyan", "orange", "accent"]


def check(c):
    """Contrast floors. Each one fails loudly if a colour is changed too far."""
    bg, lbg = c["background"], c["lighter_background"]
    r = {"text": contrast(c["foreground"], bg),
         "comments": contrast(c["muted"], bg),
         "weakest colour": min(contrast(c[k], bg) for k in SIGNAL),
         "weakest on floats": min(contrast(c[k], lbg) for k in SIGNAL),
         "text on selection": contrast(c["foreground"], c["selection"])}
    assert 11 <= r["text"] <= 17, r            # readable, not glaring
    assert r["comments"] >= 4.5, r             # WCAG AA for body text
    assert r["weakest colour"] >= 5.5, r
    assert r["weakest on floats"] >= 4.5, r
    assert r["text on selection"] >= 7, r
    return r


def toml(c):
    keys = ["accent", "selection", "muted", "background", "dark_background", "darker_background",
            "lighter_background", "foreground", "dark_foreground", "light_foreground",
            "bright_foreground", "red", "yellow", "orange", "green", "cyan", "blue", "magenta",
            "brown", "bright_red", "bright_yellow", "bright_green", "bright_cyan", "bright_blue",
            "bright_magenta"]
    return "\n".join([
        "# Deep Space: blue-black ground, ring-silver text, steel-blue accent.",
        "# Generated by tools/palettes.py. Edit that file, not this one.",
        'mode = "dark"', "",
        *[f'{k:<19}= "{c[k]}"' for k in keys], "",
        "# The ring: steel blue to lit silver, corner to corner.",
        f'hyprland_active_border   = "rgba({c["blue"][1:]}ee) rgba({c["foreground"][1:]}ee) 45deg"',
        f'hyprland_inactive_border = "rgba({c["lighter_background"][1:]}ff)"', ""])


if __name__ == "__main__":
    for k, v in check(COLORS).items():
        print(f"{k:18} {v:5.2f}:1")
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    open(os.path.join(root, "colors.toml"), "w").write(toml(COLORS))
